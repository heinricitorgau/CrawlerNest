# ── 04 environment ────────────────────────────────────────────────────────────

def parse_env_example(path: Path) -> list[tuple[str, str, str]]:
    rows, comment, section = [], [], ""
    for line in read_text(path).splitlines():
        s = line.strip()
        if s.startswith("#"):
            t = s.lstrip("# ").strip()
            if t.startswith("──"):
                section, comment = t.strip("─ ").strip(), []
            elif t:
                comment.append(t)
            continue
        m = re.match(r"^([A-Z0-9_]+)=(.*)$", s)
        if m:
            rows.append((m.group(1), mask(m.group(1), m.group(2)), (section + ": " if section else "") + " ".join(comment)))
            comment = []
        elif not s:
            comment = []
    return rows


