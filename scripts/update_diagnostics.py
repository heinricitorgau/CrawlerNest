#!/usr/bin/env python3
"""Rewrite the eight local diagnostics files in .repo-diagnostics/ from the working copy.

.repo-diagnostics/ is gitignored and nothing here pushes, uploads or writes outside it.
The files are a snapshot of this clone for a reader (or a model) who needs the state of
the repository in one place: they are regenerated, never edited by hand.

    ./.venv/bin/python scripts/update_diagnostics.py                  # collect, no tests run
    ./.venv/bin/python scripts/update_diagnostics.py --run-tests      # also run Python + Jest, record results
    ./.venv/bin/python scripts/update_diagnostics.py --run-tests all  # ... and JUnit (mvnw test)

Test results are kept in .repo-diagnostics/.state/ between runs, so a run without
--run-tests still reports the last recorded ones. JUnit results are read from the
surefire reports of the last `mvnw test`, whoever ran it.

Secrets: only *.example files and application.properties are read for configuration,
and any value whose key names a password, secret, token or key is masked. deploy/.env
and .local/*.env are never opened.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / ".repo-diagnostics"
STATE_DIR = OUT_DIR / ".state"

JAVA_DIR = REPO_ROOT / "crawlernest" / "servise_for_java"
JAVA_RESOURCES = JAVA_DIR / "src" / "main" / "resources"
WEB_DIR = REPO_ROOT / "crawlernest" / "crawlernest-web"
KB_DIR = REPO_ROOT / "crawlernest" / "crawlernest-kb"

# Judged on the key's last segment, so POSTGRES_PASSWORD and model.api-key are masked but password-reset.ttl is not.
SECRET_KEY = re.compile(r"(^|[_.-])(PASSWORD|PASSWD|SECRET|TOKEN|API[_-]?KEY|KEY|PRIVATE[_-]?KEY|CREDENTIALS?)\s*$", re.I)
GENERATED_NOTE = "Generated by `scripts/update_diagnostics.py` -- do not edit; local only, gitignored."


# ── helpers ───────────────────────────────────────────────────────────────────

def now_iso() -> str:
    return dt.datetime.now().astimezone().isoformat(timespec="seconds")


def mtime_iso(path: Path) -> str | None:
    try:
        return dt.datetime.fromtimestamp(path.stat().st_mtime).astimezone().isoformat(timespec="seconds")
    except OSError:
        return None


def rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def link(path: Path) -> str:
    """A Markdown link from a file in .repo-diagnostics/ to a repository file."""
    return f"[{rel(path)}](../{rel(path)})"


def run(cmd: list[str], cwd: Path = REPO_ROOT, timeout: int = 60, env: dict | None = None) -> tuple[int, str]:
    try:
        proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout,
                              env={**os.environ, **(env or {})})
        return proc.returncode, proc.stdout + proc.stderr
    except (OSError, subprocess.TimeoutExpired) as exc:
        return -1, str(exc)


def git(*args: str) -> str:
    code, out = run(["git", *args])
    return out.rstrip("\n") if code == 0 else ""


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""


def first_heading(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def headings(text: str, levels: tuple[int, ...] = (2, 3)) -> list[tuple[int, str]]:
    out, in_fence = [], False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            continue
        m = re.match(r"^(#{1,6})\s+(.*)", line)
        if m and not in_fence and len(m.group(1)) in levels:
            out.append((len(m.group(1)), m.group(2).strip()))
    return out


def mask(key: str, value: str) -> str:
    if value and SECRET_KEY.search(key):
        return "<masked>"
    return value


def write(name: str, content: str) -> Path:
    path = OUT_DIR / name
    path.write_text(content if content.endswith("\n") else content + "\n", encoding="utf-8")
    return path


def md_header(title: str, sources: list[str]) -> list[str]:
    lines = [f"# {title}", "", f"_{GENERATED_NOTE}_", "", f"- Generated: {now_iso()}",
             f"- Commit: `{git('rev-parse', '--short', 'HEAD') or 'unknown'}` on `{git('branch', '--show-current') or 'detached'}`"]
    if sources:
        lines.append("- Sources: " + ", ".join(f"`{s}`" for s in sources))
    return lines + [""]


# ── 01 git + tests ────────────────────────────────────────────────────────────

def git_state() -> dict:
    porcelain = git("status", "--porcelain=v1", "--branch")
    lines = porcelain.splitlines()
    branch_line = lines[0][3:] if lines and lines[0].startswith("## ") else ""
    files = []
    for line in lines[1:]:
        code, path = line[:2], line[3:]
        files.append({
            "path": path,
            "index": code[0].strip() or None,
            "worktree": code[1].strip() or None,
            "state": "untracked" if code == "??" else "staged+unstaged" if code[0] not in " ?" and code[1] != " "
            else "staged" if code[0] not in " ?" else "unstaged",
        })
    ahead = behind = None
    m = re.search(r"\[(.*?)\]", branch_line)
    if m:
        a = re.search(r"ahead (\d+)", m.group(1))
        b = re.search(r"behind (\d+)", m.group(1))
        ahead, behind = int(a.group(1)) if a else 0, int(b.group(1)) if b else 0
    elif "..." in branch_line:
        ahead = behind = 0
    return {
        "branch": git("branch", "--show-current") or None,
        "upstream": branch_line.split("...")[1].split(" ")[0] if "..." in branch_line else None,
        "ahead": ahead,
        "behind": behind,
        "head": {
            "sha": git("rev-parse", "HEAD"),
            "subject": git("log", "-1", "--format=%s"),
            "date": git("log", "-1", "--format=%cI"),
        },
        "counts": dict(Counter(f["state"] for f in files)),
        "changed_files": files,
        "diff_stat_unstaged": git("diff", "--shortstat") or None,
        "diff_stat_staged": git("diff", "--cached", "--shortstat") or None,
        "recent_commits": [dict(zip(("sha", "date", "subject"), l.split("\t", 2)))
                           for l in git("log", "-10", "--format=%h\t%cI\t%s").splitlines()],
    }


def junit_results() -> dict:
    reports = sorted((JAVA_DIR / "target" / "surefire-reports").glob("TEST-*.xml"))
    if not reports:
        return {"status": "no surefire reports", "hint": "cd crawlernest/servise_for_java && ./mvnw test"}
    totals = Counter()
    failing = []
    for report in reports:
        try:
            suite = ET.parse(report).getroot()
        except ET.ParseError:
            continue
        for k in ("tests", "failures", "errors", "skipped"):
            totals[k] += int(float(suite.get(k, 0)))
        for case in suite.iter("testcase"):
            if case.find("failure") is not None or case.find("error") is not None:
                failing.append(f"{case.get('classname')}#{case.get('name')}")
    newest = max(reports, key=lambda p: p.stat().st_mtime)
    return {
        "status": "passed" if totals["failures"] + totals["errors"] == 0 else "failed",
        "recorded_at": mtime_iso(newest),
        "suites": len(reports),
        **dict(totals),
        "failing": failing[:50],
        "source": rel(newest.parent),
        "note": "Surefire reports persist across runs: a suite deleted since the last mvnw test still has a report "
                "until `mvnw clean`.",
    }


def run_python_tests() -> dict:
    started = now_iso()
    code, out = run([sys.executable, "crawlernest/crawlernest-tests/run_tests.py"], timeout=1800)
    ran = re.findall(r"Ran (\d+) tests? in ([\d.]+)s", out)
    final = re.findall(r"^(OK.*|FAILED.*)$", out, re.M)
    return {
        "status": "passed" if code == 0 else "failed",
        "exit_code": code,
        "recorded_at": started,
        "tests": int(ran[-1][0]) if ran else None,
        "duration_s": float(ran[-1][1]) if ran else None,
        "summary": final[-1] if final else None,
        "postgres_tests": "enabled" if os.environ.get("CRAWLERNEST_RUN_PG_TESTS") == "1"
        else "skipped (CRAWLERNEST_RUN_PG_TESTS unset)",
        "output_tail": out.splitlines()[-15:],
    }


def run_jest() -> dict:
    started = now_iso()
    out_file = STATE_DIR / "jest-output.json"
    code, out = run(["npx", "--no-install", "jest", "--ci", "--json", f"--outputFile={out_file}"], cwd=WEB_DIR,
                    timeout=1800)
    result = {"status": "passed" if code == 0 else "failed", "exit_code": code, "recorded_at": started}
    try:
        data = json.loads(out_file.read_text())
        result.update({
            "suites": data.get("numTotalTestSuites"),
            "tests": data.get("numTotalTests"),
            "passed": data.get("numPassedTests"),
            "failed": data.get("numFailedTests"),
            "pending": data.get("numPendingTests"),
            "failing_suites": [rel(Path(s["name"])) for s in data.get("testResults", []) if s.get("status") == "failed"],
        })
    except (OSError, ValueError, KeyError):
        result["output_tail"] = out.splitlines()[-15:]
    return result


def run_junit() -> dict:
    code, out = run(["./mvnw", "-q", "test"], cwd=JAVA_DIR, timeout=3600)
    result = junit_results()
    result["exit_code"] = code
    if code != 0 and result.get("status") == "passed":
        result["status"] = "failed"
        result["output_tail"] = out.splitlines()[-15:]
    return result


def build_01(run_suites: set[str]) -> dict:
    state_file = STATE_DIR / "last-test-runs.json"
    try:
        recorded = json.loads(state_file.read_text())
    except (OSError, ValueError):
        recorded = {}
    if "python" in run_suites:
        print("  running Python tests ...", flush=True)
        recorded["python"] = run_python_tests()
    if "jest" in run_suites:
        print("  running Jest ...", flush=True)
        recorded["jest"] = run_jest()
    if "junit" in run_suites:
        print("  running JUnit (mvnw test) ...", flush=True)
        recorded["junit"] = run_junit()
    state_file.write_text(json.dumps(recorded, indent=2, ensure_ascii=False))
    never = {"status": "not recorded", "hint": "scripts/update_diagnostics.py --run-tests"}
    return {
        "_note": GENERATED_NOTE,
        "generated_at": now_iso(),
        "git": git_state(),
        "tests": {
            "junit": recorded.get("junit") if "junit" in run_suites else junit_results(),
            "jest": recorded.get("jest", never),
            "python": recorded.get("python", never),
        },
    }


# ── 02 schema + migrations ────────────────────────────────────────────────────

DDL = re.compile(r"^\s*(CREATE|ALTER|DROP)\s+(?:OR\s+REPLACE\s+)?(?:UNIQUE\s+)?(?:MATERIALIZED\s+)?"
                 r"(SCHEMA|TABLE|VIEW|INDEX|FUNCTION|TRIGGER|TYPE|SEQUENCE|EXTENSION)\s+"
                 r"(?:IF\s+(?:NOT\s+)?EXISTS\s+)?(?:CONCURRENTLY\s+)?([\w.\"]+)", re.I | re.M)


def sql_summary(path: Path) -> tuple[str, Counter, list[str]]:
    text = read_text(path)
    lead = []
    for line in text.splitlines():
        if line.startswith("--"):
            lead.append(line.lstrip("- ").rstrip())
        elif line.strip():
            break
    statements = [(m.group(1).upper(), m.group(2).upper(), m.group(3).strip('"')) for m in DDL.finditer(text)]
    kinds = Counter(f"{verb} {kind}" for verb, kind, _ in statements)
    objects = [f"{verb} {kind} `{name}`" for verb, kind, name in statements]
    return " ".join(l for l in lead if l)[:600], kinds, objects


def build_02() -> str:
    migration_dirs = sorted({p.parent for p in JAVA_RESOURCES.rglob("V*__*.sql")})
    schema_dir = REPO_ROOT / "crawlernest" / "crawlernest-schema"
    props = read_text(JAVA_RESOURCES / "application.properties")
    flyway_lines = [l for l in props.splitlines() if "flyway" in l.lower() and not l.lstrip().startswith("#")]
    out = md_header("DB schema and migrations", [rel(JAVA_RESOURCES / "db"), rel(schema_dir)])
    out += ["Two DDL sources: Flyway-style versioned migrations owned by the Spring Boot API (auth / desk schema), "
            "and the warehouse DDL in `crawlernest-schema/`, applied by `run_pipeline bootstrap-postgres`.", ""]
    if not migration_dirs:
        out += ["> No `V*__*.sql` migrations found under `src/main/resources/`.", ""]
    for d in migration_dirs:
        files = sorted(d.glob("V*__*.sql"), key=lambda p: int(re.match(r"V(\d+)", p.name).group(1)))
        out += [f"## Versioned migrations: `{rel(d)}/` ({len(files)})", ""]
        if flyway_lines:
            out += ["Configuration (`application.properties`):", "", "```properties",
                    *[re.sub(r"=(.*)", lambda m: "=" + mask(l.split("=")[0], m.group(1)), l) for l in flyway_lines],
                    "```", ""]
        versions = [int(re.match(r"V(\d+)", p.name).group(1)) for p in files]
        gaps = sorted(set(range(1, max(versions) + 1)) - set(versions)) if versions else []
        if gaps:
            out += [f"> Version gaps: {', '.join(f'V{g:03d}' for g in gaps)}", ""]
        for f in files:
            lead, kinds, objects = sql_summary(f)
            out += [f"### {f.name}", "", f"- File: {link(f)} (modified {mtime_iso(f)})"]
            if lead:
                out.append(f"- Header: {lead}")
            out.append("- Statements: " + (", ".join(f"{k} ×{n}" for k, n in sorted(kinds.items())) or "none parsed"))
            out += [f"  - {o}" for o in objects[:40]]
            out.append("")
    files = sorted(schema_dir.glob("*.sql"))
    out += [f"## Warehouse DDL: `{rel(schema_dir)}/` ({len(files)} files)", "",
            "| File | Lines | Tables | Views | Indexes | Other | Modified |", "|---|---:|---:|---:|---:|---:|---|"]
    detail = []
    for f in files:
        _, kinds, objects = sql_summary(f)
        tables = sum(n for k, n in kinds.items() if k.endswith("TABLE") and k.startswith("CREATE"))
        views = sum(n for k, n in kinds.items() if k.endswith("VIEW"))
        idx = sum(n for k, n in kinds.items() if k.endswith("INDEX"))
        other = sum(kinds.values()) - tables - views - idx
        out.append(f"| {link(f)} | {len(read_text(f).splitlines())} | {tables} | {views} | {idx} | {other} | "
                   f"{(mtime_iso(f) or '')[:10]} |")
        created = sorted({o.split("`")[1] for o in objects if o.startswith("CREATE") and ("TABLE" in o or "VIEW" in o)})
        if created:
            detail.append(f"- **{f.name}**: " + ", ".join(f"`{c}`" for c in created))
    out += ["", "### Tables and views created, per file", "", *detail, ""]
    return "\n".join(out)


# ── 03 architecture + API ─────────────────────────────────────────────────────

MAPPING = re.compile(r"@(Get|Post|Put|Delete|Patch|Request)Mapping\s*(?:\(([^)]*)\))?")


def mapping_paths(args: str | None) -> list[str]:
    if not args:
        return [""]
    found = re.findall(r'"([^"]*)"', args)
    return found or [""]


def java_endpoints() -> list[tuple[str, str, str, str]]:
    rows = []
    for f in sorted((JAVA_DIR / "src" / "main" / "java").rglob("*.java")):
        text = read_text(f)
        if "@RestController" not in text and "@Controller" not in text:
            continue
        class_pos = re.search(r"^[ \t]*(?:(?:public|final|abstract)\s+)*class\s+(\w+)", text, re.M)
        if not class_pos:
            continue
        head = text[:class_pos.start()]
        base = ""
        for m in MAPPING.finditer(head):
            if m.group(1) == "Request":
                base = mapping_paths(m.group(2))[0]
        body = text[class_pos.end():]
        for m in MAPPING.finditer(body):
            verb = m.group(1).upper()
            if verb == "REQUEST":
                mm = re.search(r"RequestMethod\.(\w+)", m.group(2) or "")
                verb = mm.group(1) if mm else "ANY"
            method = re.search(r"\b(\w+)\s*\(", body[m.end():m.end() + 600].split("{")[0].replace("@", " @"))
            name = ""
            sig = body[m.end():m.end() + 600]
            mname = re.search(r"(?:public|protected|private)?\s*[\w<>\[\], ?]+\s+(\w+)\s*\(", sig)
            if mname:
                name = mname.group(1)
            elif method:
                name = method.group(1)
            for p in mapping_paths(m.group(2)):
                rows.append((verb, (base + p) or "/", f"{class_pos.group(1)}.{name}", rel(f)))
    return rows


def web_routes() -> list[tuple[str, str]]:
    api = WEB_DIR / "src" / "app" / "api"
    rows = []
    for f in sorted(api.rglob("route.ts")):
        verbs = re.findall(r"export\s+(?:async\s+)?(?:function|const)\s+(GET|POST|PUT|DELETE|PATCH)\b", read_text(f))
        route = "/api/" + f.parent.relative_to(api).as_posix()
        rows.append((route, ", ".join(verbs) or "?"))
    return rows


