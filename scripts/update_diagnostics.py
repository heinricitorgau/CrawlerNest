def assert_ignored() -> None:
    code, _ = run(["git", "check-ignore", "-q", ".repo-diagnostics/01-git-test-status.json"])
    if code != 0:
        sys.exit("refusing to write: .repo-diagnostics/ is not gitignored (add `.repo-diagnostics/` to .gitignore)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--run-tests", nargs="?", const="python,jest", default="",
                    help="run suites and record results: comma list of python,jest,junit or 'all' (default python,jest)")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()
    suites = {"python", "jest", "junit"} if args.run_tests == "all" else {s for s in args.run_tests.split(",") if s}
    if suites - {"python", "jest", "junit"}:
        ap.error(f"unknown suite(s): {', '.join(suites - {'python', 'jest', 'junit'})}")

    assert_ignored()
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    s01 = build_01(suites)
    jobs = [
        ("01-git-test-status.json", lambda: json.dumps(s01, indent=2, ensure_ascii=False)),
        ("02-db-schema-migrations.md", build_02),
        ("03-architecture-api-docs.md", build_03),
        ("04-environment-config-template.md", build_04),
        ("05-issues-backlog-summary.md", lambda: build_05(s01["git"])),
        ("06-cicd-workflow-rules.md", build_06),
        ("07-llm-rubric-evals.json", lambda: json.dumps(build_07(), indent=2, ensure_ascii=False)),
        ("08-entity-warehouse-aliases.md", build_08),
    ]
    failed = 0
    for name, build in jobs:
        try:
            path = write(name, build())
            if not args.quiet:
                print(f"  wrote {rel(path)} ({path.stat().st_size:,} bytes)")
        except Exception as exc:  # one broken section must not stop the other seven
            failed += 1
            write(name, f"generation failed: {type(exc).__name__}: {exc}\n")
            print(f"  FAILED {name}: {type(exc).__name__}: {exc}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
