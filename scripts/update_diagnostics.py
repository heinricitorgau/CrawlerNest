def parse_workflow(text: str) -> dict:
    """Enough of a GitHub Actions file for a summary, without a YAML parser: triggers, jobs, steps."""
    lines = text.splitlines()
    wf = {"name": "", "on": [], "jobs": []}
    section, job, step = None, None, None
    for i, line in enumerate(lines):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        s = line.strip()
        if indent == 0:
            section = s.split(":")[0]
            if section == "name":
                wf["name"] = s.split(":", 1)[1].strip().strip('"')
            continue
        if section == "on":
            wf["on"].append(line[2:])
        elif section == "jobs":
            if indent == 2 and s.endswith(":"):
                job = {"id": s[:-1], "name": "", "runs_on": "", "services": [], "env": [], "steps": [], "needs": ""}
                wf["jobs"].append(job)
                step = None
            elif job and indent == 4:
                key = s.split(":")[0]
                val = s.split(":", 1)[1].strip() if ":" in s else ""
                if key == "name":
                    job["name"] = val.strip('"')
                elif key == "runs-on":
                    job["runs_on"] = val
                elif key == "needs":
                    job["needs"] = val
                job["_block"] = key
            elif job and indent == 6 and job.get("_block") == "services" and s.endswith(":"):
                job["services"].append(s[:-1])
            elif job and indent == 6 and job.get("_block") == "env" and ":" in s:
                job["env"].append(s.split(":")[0] + "=" + mask(s.split(":")[0], s.split(":", 1)[1].strip()))
            elif job and job.get("_block") == "steps" and s.startswith("- "):
                step = {"name": "", "uses": "", "run": ""}
                job["steps"].append(step)
                s = s[2:]
            if job and job.get("_block") == "steps" and step is not None and indent >= 6:
                if s.startswith("name:"):
                    step["name"] = s[5:].strip().strip('"')
                elif s.startswith("uses:"):
                    step["uses"] = s[5:].strip()
                elif s.startswith("run:"):
                    v = s[4:].strip()
                    if v in ("|", ">", "|-", ">-"):
                        body = []
                        for nxt in lines[i + 1:]:
                            if nxt.strip() and len(nxt) - len(nxt.lstrip()) <= indent:
                                break
                            if nxt.strip():
                                body.append(nxt.strip())
                        v = " ; ".join(body)
                    step["run"] = v
    for j in wf["jobs"]:
        j.pop("_block", None)
    return wf


