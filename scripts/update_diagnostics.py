    out += ["", "Fixed properties:", "", "```properties", *plain, "```"]

    referenced = set()
    for root in (REPO_ROOT / "crawlernest", REPO_ROOT / "scripts", REPO_ROOT / "deploy"):
        code, txt = run(["git", "grep", "-h", "-o", "-I", "-E", r"CRAWLERNEST_[A-Z0-9_]+", "--", rel(root)])
