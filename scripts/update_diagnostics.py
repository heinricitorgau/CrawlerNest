def ts_string_arrays(text: str) -> dict:
    out = {}
    for m in re.finditer(r"export const (\w+)\s*=\s*\[(.*?)\]", text, re.S):
        out[m.group(1)] = re.findall(r'"([^"]*)"', m.group(2))
    for m in re.finditer(r"(\w+):\s*\[(.*?)\]", text, re.S):
        vals = re.findall(r'"([^"]*)"', m.group(2))
        if vals:
            out[m.group(1)] = vals
    return out


