def function_source(text: str, name: str) -> str:
    m = re.search(rf"^([ \t]*)(?:@staticmethod\s*\n[ \t]*)?def {name}\(.*?(?=^\1(?:def |@|class )|\Z)", text, re.S | re.M)
    return m.group(0).rstrip() if m else ""


